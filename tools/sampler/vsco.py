"""Write an SFZ program for a VSCO 2 Community Edition folder of recordings.

VSCO ships WAV files named like Sum_SHTrumpet_sus_A#3_v1_rr1.wav (note, velocity layer, round robin) and no SFZ map.
This reads the names and writes the map a sampler needs: each recording plays its own note and the keys halfway to its
neighbours, with its velocity layer and round-robin position. Notes above the highest recording are repitched up from it.

    python3 tools/sampler/vsco.py SAMPLE_DIR OUT.sfz [--top 79]
"""
import os
import re
import sys

NAMES = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}
FILE = re.compile(r"_(?P<note>[A-G]#?)(?P<oct>-?\d)_v(?P<vel>\d+)_rr(?P<rr>\d+)\.wav$")


def midi_key(note, octave):
    """Middle C is C4 = 60."""
    return 12 * (octave + 1) + NAMES[note]


def parse_name(name):
    m = FILE.search(name)
    if not m:
        return None
    return {"file": name, "key": midi_key(m["note"], int(m["oct"])), "vel": int(m["vel"]), "rr": int(m["rr"])}


def regions(names, bottom=0, top=127):
    """Region dicts for every recording. Velocity layers split 1..127 evenly; round robins share a key and rotate."""
    recs = [r for r in map(parse_name, names) if r]
    if not recs:
        raise ValueError("no recordings with note, velocity and round-robin names")
    keys = sorted({r["key"] for r in recs})
    vels = sorted({r["vel"] for r in recs})
    rrs = max(r["rr"] for r in recs)
    out = []
    for r in recs:
        i = keys.index(r["key"])
        lo = bottom if i == 0 else (keys[i - 1] + r["key"]) // 2 + 1
        hi = top if i == len(keys) - 1 else (r["key"] + keys[i + 1]) // 2
        j = vels.index(r["vel"])
        lovel = 1 if j == 0 else round(127 * j / len(vels)) + 1
        hivel = 127 if j == len(vels) - 1 else round(127 * (j + 1) / len(vels))
        out.append({**r, "lokey": lo, "hikey": hi, "lovel": lovel, "hivel": hivel, "seq_length": rrs})
    return sorted(out, key=lambda r: (r["key"], r["vel"], r["rr"]))


def sfz_text(names, sample_dir_in_sfz="sus", release=0.35, top=127):
    lines = ["// generated by tools/sampler/vsco.py from the recording names", "<group> ampeg_release=%g loop_mode=no_loop" % release]
    for r in regions(names, top=top):
        lines.append(
            "<region> sample=%s/%s lokey=%d hikey=%d pitch_keycenter=%d lovel=%d hivel=%d seq_length=%d seq_position=%d"
            % (sample_dir_in_sfz, r["file"], r["lokey"], r["hikey"], r["key"], r["lovel"], r["hivel"], r["seq_length"], r["rr"]))
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    top = int(argv[argv.index("--top") + 1]) if "--top" in argv else 127
    names = sorted(n for n in os.listdir(argv[0]) if n.endswith(".wav"))
    open(argv[1], "w").write(sfz_text(names, sample_dir_in_sfz=os.path.basename(os.path.abspath(argv[0])), top=top))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
