/**
 * BAND TESTS — ScriptHammer steampunk robot band & track casting
 */
import { describe, it } from 'node:test';
import assert from 'node:assert';
import { existsSync, statSync } from 'node:fs';
import path from 'node:path';
import {
  bandMembers,
  trackCasting,
  getMusicianForTrack,
  getMusicianByName,
  getAllMusicians,
  getPortraitPath,
  getLogoPath
} from '../src/band.js';

describe('band & casting', () => {
  it('all seven band members are defined with required attributes', () => {
    assert.equal(bandMembers.length, 7);
    const requiredKeys = ['name', 'instrument', 'role', 'personality', 'look'];
    for (const member of bandMembers) {
      for (const k of requiredKeys) {
        assert.ok(member[k], `Member ${member.name} missing ${k}`);
        assert.equal(typeof member[k], 'string');
      }
    }
  });

  it('all seven bots are cast across tracks or master', () => {
    const castNames = new Set();
    for (const cast of trackCasting) {
      if (cast.musician) castNames.add(cast.musician);
      if (cast.guest) castNames.add(cast.guest);
    }
    for (const member of bandMembers) {
      assert.ok(castNames.has(member.name), `Band member ${member.name} must be cast`);
    }
  });

  it('every track (1-8 and master) has a musician assigned', () => {
    for (let trackNum = 1; trackNum <= 8; trackNum++) {
      const casting = getMusicianForTrack(trackNum);
      assert.ok(casting, `Track ${trackNum} has casting`);
      assert.ok(casting.musician, `Track ${trackNum} has primary musician`);
    }
    const master = getMusicianForTrack('master');
    assert.ok(master && master.musician && master.musician.name === 'Form', 'Master is Form');
  });

  it('tracks 1-4 Kick, Snare, Hats, Perc are cast to Crash', () => {
    for (let t = 1; t <= 4; t++) {
      const { musician } = getMusicianForTrack(t);
      assert.equal(musician.name, 'Crash');
    }
  });

  it('track 5 Bass is Chops, track 6 Keys is Ivory, track 7 Bed is Reed', () => {
    assert.equal(getMusicianForTrack(5).musician.name, 'Chops');
    assert.equal(getMusicianForTrack(6).musician.name, 'Ivory');
    assert.equal(getMusicianForTrack(7).musician.name, 'Reed');
  });

  it('track 8 Jingle is Verse with Brass beside him', () => {
    const { musician, guest } = getMusicianForTrack(8);
    assert.equal(musician.name, 'Verse');
    assert.equal(guest.name, 'Brass');
  });

  it('every portrait file exists and is under 80 KB (when assets present)', (t) => {
    const assetsDir = path.resolve('assets/band');
    if (!existsSync(assetsDir) || !existsSync(path.join(assetsDir, 'crash.webp'))) {
      t.skip('assets/band/*.webp not yet generated by hub');
      return;
    }
    for (const member of bandMembers) {
      const file = path.join(assetsDir, `${member.name.toLowerCase()}.webp`);
      assert.ok(existsSync(file), `Portrait file exists: ${file}`);
      const stats = statSync(file);
      assert.ok(stats.size < 80 * 1024, `Portrait ${file} must be < 80KB (got ${stats.size})`);
    }
    const logoFile = path.join(assetsDir, 'logo.webp');
    assert.ok(existsSync(logoFile), `Logo exists: ${logoFile}`);
    assert.ok(statSync(logoFile).size < 80 * 1024, `Logo must be < 80KB (got ${statSync(logoFile).size})`);
  });
});
